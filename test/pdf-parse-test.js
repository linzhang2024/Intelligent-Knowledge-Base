async function testPDFParse() {
  console.log('='.repeat(60));
  console.log('PDF-Parse 测试');
  console.log('='.repeat(60));
  console.log(`Node.js 版本: ${process.version}`);
  console.log(`测试时间: ${new Date().toLocaleString('zh-CN')}`);
  console.log('');

  const testResults = [];

  console.log('测试 1: 测试简单 PDF 结构（空 PDF）');
  const emptyPDF = createSimpleTestPDF();
  console.log(`  空 PDF 大小: ${emptyPDF.length} 字节`);
  
  try {
    const parser = new PDFParse({ data: emptyPDF });
    console.log('  ✓ PDFParse 实例创建成功');
    
    console.log('  尝试获取文本...');
    const textResult = await parser.getText();
    console.log(`  ✓ 文本获取成功，页数: ${textResult.total}`);
    console.log(`  ✓ 文本内容长度: ${textResult.text.length}`);
    
    await parser.destroy();
    console.log('  ✓ 解析器销毁成功');
    testResults.push({ test: '空PDF解析', passed: true, message: `页数: ${textResult.total}, 文本长度: ${textResult.text.length}` });
  } catch (error) {
    console.log(`  ✗ 解析失败: ${error.message}`);
    testResults.push({ test: '空PDF解析', passed: false, message: error.message });
    
    if (error instanceof PasswordException) {
      console.log('  → 错误类型: PasswordException (PDF已加密)');
    } else if (error instanceof InvalidPDFException) {
      console.log('  → 错误类型: InvalidPDFException (无效PDF)');
    } else if (error instanceof FormatError) {
      console.log('  → 错误类型: FormatError (格式错误)');
    }
  }

  console.log('');
  console.log('测试 2: 测试无效文件');
  const invalidBuffer = Buffer.from('This is not a PDF file');
  
  try {
    const parser = new PDFParse({ data: invalidBuffer });
    const textResult = await parser.getText();
    await parser.destroy();
    console.log(`  ✗ 意外: 无效文件解析成功`);
    testResults.push({ test: '无效文件解析', passed: false, message: '应该抛出异常' });
  } catch (error) {
    console.log(`  ✓ 正确抛出异常: ${error.message}`);
    testResults.push({ test: '无效文件解析', passed: true, message: '正确抛出异常' });
  }

  console.log('');
  console.log('测试 3: 测试更完整的 PDF 结构');
  const validPDF = createValidTestPDF();
  console.log(`  测试 PDF 大小: ${validPDF.length} 字节`);
  
  try {
    const parser = new PDFParse({ data: validPDF });
    console.log('  ✓ PDFParse 实例创建成功');
    
    console.log('  尝试获取信息...');
    const infoResult = await parser.getInfo({ parsePageInfo: true });
    console.log(`  ✓ 信息获取成功，总页数: ${infoResult.total}`);
    
    console.log('  尝试获取文本...');
    const textResult = await parser.getText();
    console.log(`  ✓ 文本获取成功，页数: ${textResult.total}`);
    console.log(`  ✓ 文本内容: "${textResult.text}"`);
    
    await parser.destroy();
    console.log('  ✓ 解析器销毁成功');
    testResults.push({ test: '完整PDF解析', passed: true, message: `页数: ${infoResult.total}` });
  } catch (error) {
    console.log(`  ✗ 解析失败: ${error.message}`);
    testResults.push({ test: '完整PDF解析', passed: false, message: error.message });
  }

  console.log('');
  console.log('='.repeat(60));
  console.log('测试结果汇总');
  console.log('='.repeat(60));
  
  const passed = testResults.filter(r => r.passed).length;
  const failed = testResults.filter(r => !r.passed).length;
  
  console.log(`\n总测试数: ${testResults.length}`);
  console.log(`通过: ${passed}`);
  console.log(`失败: ${failed}`);
  
  if (failed > 0) {
    console.log('\n失败的测试:');
    testResults.filter(r => !r.passed).forEach((r, i) => {
      console.log(`  ${i + 1}. ${r.test}: ${r.message}`);
    });
  }
  
  console.log('\n' + '='.repeat(60));
  if (failed === 0) {
    console.log('✅ 所有测试通过！');
  } else {
    console.log('❌ 部分测试失败！');
  }
  console.log('='.repeat(60));
}

testPDFParse().catch(console.error);
